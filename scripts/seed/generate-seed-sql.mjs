// Generates supabase/seed/base.sql and supabase/seed/demo.sql from the JSON seed data so the
// database seed and the frontend's bundled defaults can never drift apart.
//
//   npm run seed:generate   → (re)write the SQL files
//   npm run seed:check      → fail if the committed SQL is out of date (used by `npm run check`)
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const seedDir = path.join(root, 'supabase/seed');
const checkOnly = process.argv.includes('--check');

const jsonLiteral = (value) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

async function readJson(relative) {
  return JSON.parse(await readFile(path.join(seedDir, relative), 'utf8'));
}

async function buildBaseSql() {
  const { settings } = await readJson('data/base/site-settings.json');
  const rows = Object.entries(settings).map(
    ([key, value]) => `  ('${key}', ${jsonLiteral(value)})`,
  );
  return `-- ════════════════════════════════════════════════════════════════════════════
-- MALEK STORE · BASE seed (real, owner-supplied configuration — NOT demo data)
-- GENERATED by scripts/seed/generate-seed-sql.mjs from supabase/seed/data/base/site-settings.json.
-- Do not edit by hand: edit the JSON and run \`npm run seed:generate\`.
--
-- Idempotent: existing published settings are never overwritten (admin edits win).
-- Run once after migrations: supabase db reset (local) or paste into the SQL editor (hosted).
-- ════════════════════════════════════════════════════════════════════════════

insert into public.site_settings (key, value) values
${rows.join(',\n')}
on conflict (key) do nothing;
`;
}

async function buildDemoSql() {
  const manifest = await readJson('data/demo/manifest.json');
  const sections = [];
  for (const dataset of manifest.datasets) {
    const data = await readJson(path.join('data/demo', dataset.file));
    const rows = data.rows.map((row) => `  (${jsonLiteral(row)})`);
    sections.push(
      `-- dataset: ${dataset.name} → ${dataset.table}\n` +
        `insert into ${dataset.table}\nselect * from jsonb_populate_recordset(null::${dataset.table}, jsonb_build_array(\n${rows.join(',\n')}\n))\non conflict do nothing;\n`,
    );
  }
  return `-- ════════════════════════════════════════════════════════════════════════════
-- MALEK STORE · DEMO seed (sample data for previews — every row has is_demo = true)
-- GENERATED by scripts/seed/generate-seed-sql.mjs from supabase/seed/data/demo/manifest.json.
-- Do not edit by hand. Remove at any time with: select public.delete_all_demo_data();
-- Never run this against a production database you intend to launch without demo cleanup.
-- ════════════════════════════════════════════════════════════════════════════
${sections.length === 0 ? '\n-- No demo datasets yet (the demo catalog, offers and campaigns arrive in Phase 02).\nselect 1;\n' : `\n${sections.join('\n')}`}`;
}

async function main() {
  const outputs = [
    [path.join(seedDir, 'base.sql'), await buildBaseSql()],
    [path.join(seedDir, 'demo.sql'), await buildDemoSql()],
  ];
  let stale = false;
  for (const [file, content] of outputs) {
    if (checkOnly) {
      const current = await readFile(file, 'utf8').catch(() => '');
      if (current !== content) {
        console.error(`✗ ${path.relative(root, file)} is out of date — run npm run seed:generate`);
        stale = true;
      }
    } else {
      await writeFile(file, content);
      console.log(`✓ wrote ${path.relative(root, file)}`);
    }
  }
  if (stale) process.exit(1);
  if (checkOnly) console.log('✓ seed SQL is up to date');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
