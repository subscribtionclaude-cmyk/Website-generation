// Generates supabase/seed/base.sql and supabase/seed/demo.sql from the JSON seed data so the
// database seed and the frontend's bundled data can never drift apart.
//
//   npm run seed:generate   → rebuild demo catalog/media, then (re)write the SQL files
//   npm run seed:check      → fail if anything generated is out of date (used by `npm run check`)
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const seedDir = path.join(root, 'supabase/seed');
const checkOnly = process.argv.includes('--check');

execFileSync(
  process.execPath,
  [path.join(root, 'scripts/seed/build-demo-data.mjs'), ...(checkOnly ? ['--check'] : [])],
  {
    stdio: 'inherit',
  },
);

const q = (value) =>
  value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const jsonLiteral = (value) =>
  value === null || value === undefined
    ? 'null'
    : `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const num = (value) => (value === null || value === undefined ? 'null' : String(value));
const bool = (value) => (value ? 'true' : 'false');
/** Deterministic UUID for a demo key (same value in every environment → idempotent seeds). */
const id = (key) => `md5(${q(`malek-demo:${key}`)})::uuid`;

const RELATIVE = /^([+-])(\d+)([dhm])$/;
function time(value) {
  if (value === null || value === undefined) return 'null';
  const match = RELATIVE.exec(value);
  if (!match) return `${q(value)}::timestamptz`;
  const unit = { d: 'days', h: 'hours', m: 'minutes' }[match[3]];
  return `(now() ${match[1]} interval '${match[2]} ${unit}')`;
}
const date = (value) => (value === null || value === undefined ? 'null' : `(${time(value)})::date`);

async function readJson(relative) {
  return JSON.parse(await readFile(path.join(seedDir, relative), 'utf8'));
}

function insert(table, columns, rows, conflict = 'on conflict do nothing') {
  if (rows.length === 0) return '';
  return `insert into ${table} (${columns.join(', ')}) values\n${rows.map((r) => `  (${r.join(', ')})`).join(',\n')}\n${conflict};\n`;
}

async function buildBaseSql() {
  const { settings } = await readJson('data/base/site-settings.json');
  const { sections } = await readJson('data/base/page-sections.json');
  const settingRows = Object.entries(settings).map(
    ([key, value]) => `  ('${key}', ${jsonLiteral(value)})`,
  );
  return `-- ════════════════════════════════════════════════════════════════════════════
-- MALEK STORE · BASE seed (real, owner-supplied configuration — NOT demo data)
-- GENERATED by scripts/seed/generate-seed-sql.mjs from supabase/seed/data/base/*.json.
-- Do not edit by hand: edit the JSON and run \`npm run seed:generate\`.
--
-- Idempotent: existing published settings and page sections are never overwritten (admin edits win).
-- Run after migrations: supabase db reset (local) or paste into the SQL editor (hosted).
-- ════════════════════════════════════════════════════════════════════════════

insert into public.site_settings (key, value) values
${settingRows.join(',\n')}
on conflict (key) do nothing;

${insert(
  'public.page_sections',
  ['page_key', 'key', 'type', 'sort_order', 'is_visible', 'props'],
  sections.map((s) => [
    q(s.pageKey),
    q(s.key),
    q(s.type),
    num(s.sortOrder),
    bool(s.isVisible),
    jsonLiteral(s.props),
  ]),
  'on conflict (page_key, key) do nothing',
)}`;
}

async function buildDemoSql() {
  const catalog = await readJson('data/demo/catalog.json');
  const out = [];
  const categoriesSorted = [...catalog.categories].sort(
    (a, b) => (a.parentSlug ? 1 : 0) - (b.parentSlug ? 1 : 0),
  );

  out.push(
    insert(
      'public.brands',
      ['id', 'slug', 'name', 'description', 'logo_url', 'sort_order', 'is_demo'],
      catalog.brands.map((b) => [
        id(b.id),
        q(b.slug),
        jsonLiteral(b.name),
        jsonLiteral(b.description),
        q(b.logoUrl),
        num(b.sortOrder),
        'true',
      ]),
    ),
  );

  out.push(
    insert(
      'public.categories',
      [
        'id',
        'parent_id',
        'slug',
        'name',
        'description',
        'icon',
        'image_url',
        'sort_order',
        'show_in_nav',
        'show_on_home',
        'show_in_shop',
        'show_in_category_grid',
        'is_demo',
      ],
      categoriesSorted.map((c) => [
        id(c.id),
        c.parentSlug ? id(`demo-category-${c.parentSlug}`) : 'null',
        q(c.slug),
        jsonLiteral(c.name),
        jsonLiteral(c.description),
        q(c.icon),
        q(c.imageUrl),
        num(c.sortOrder),
        bool(c.showInNav),
        bool(c.showOnHome),
        bool(c.showInShop),
        bool(c.showInCategoryGrid),
        'true',
      ]),
    ),
  );

  const products = [],
    productCategories = [],
    brandCategories = new Set(),
    options = [],
    values = [],
    variants = [],
    vov = [],
    media = [],
    groups = [],
    specs = [],
    relations = [],
    rankings = [];
  for (const p of catalog.products) {
    const pid = id(p.id);
    products.push([
      pid,
      q(p.slug),
      id(`demo-brand-${p.brandSlug}`),
      q(p.model),
      jsonLiteral(p.name),
      jsonLiteral(p.subtitle),
      jsonLiteral(p.description),
      jsonLiteral(p.warranty),
      q(p.availabilityState),
      "'published'",
      bool(p.isNew),
      bool(p.isFeatured),
      date(p.releaseDate),
      q(p.keywords),
      jsonLiteral(p.seo.title),
      jsonLiteral(p.seo.description),
      'now()',
      'true',
    ]);
    p.categorySlugs.forEach((slug, i) => {
      productCategories.push([pid, id(`demo-category-${slug}`), bool(i === 0), num(i)]);
      brandCategories.add(`${p.brandSlug}|${slug}`);
    });
    p.options.forEach((o, oi) => {
      options.push([id(`${p.id}:opt:${o.key}`), pid, q(o.key), jsonLiteral(o.name), num(oi)]);
      o.values.forEach((v, vi) =>
        values.push([
          id(`${p.id}:opt:${o.key}:${v.key}`),
          id(`${p.id}:opt:${o.key}`),
          q(v.key),
          jsonLiteral(v.label),
          q(v.hex),
          num(vi),
        ]),
      );
    });
    p.variants.forEach((v, i) => {
      variants.push([
        id(v.id),
        pid,
        q(v.sku),
        num(v.price),
        num(v.compareAtPrice),
        num(v.stock),
        num(v.lowStockThreshold),
        bool(v.isActive),
        bool(v.isDefault),
        jsonLiteral(v.warranty),
        num(i),
        'true',
      ]);
      for (const [key, valueKey] of Object.entries(v.options)) {
        vov.push([id(v.id), id(`${p.id}:opt:${key}`), id(`${p.id}:opt:${key}:${valueKey}`)]);
      }
    });
    for (const m of p.media) {
      media.push([
        id(m.id),
        pid,
        m.colorKey ? id(`${p.id}:opt:color:${m.colorKey}`) : 'null',
        q(m.kind),
        q(m.url),
        q(m.posterUrl),
        jsonLiteral(m.alt),
        num(m.width),
        num(m.height),
        num(m.sortOrder),
        bool(m.isCover),
        'true',
      ]);
    }
    p.specGroups.forEach((g, gi) => {
      groups.push([id(`${p.id}:spec:${g.key}`), pid, q(g.key), jsonLiteral(g.title), num(gi)]);
      g.items.forEach((s, si) =>
        specs.push([
          id(`${p.id}:spec:${g.key}:${s.key}`),
          id(`${p.id}:spec:${g.key}`),
          q(s.key),
          jsonLiteral(s.label),
          jsonLiteral(s.value),
          num(si),
        ]),
      );
    });
    for (const r of p.relations)
      relations.push([pid, id(`demo-product-${r.slug}`), q(r.kind), num(r.sortOrder)]);
    rankings.push([pid, num(p.bestSellerScore), "'demo'"]);
  }

  out.push(
    insert(
      'public.brand_categories',
      ['brand_id', 'category_id'],
      [...brandCategories].map((key) => {
        const [b, c] = key.split('|');
        return [id(`demo-brand-${b}`), id(`demo-category-${c}`)];
      }),
    ),
  );
  out.push(
    insert(
      'public.products',
      [
        'id',
        'slug',
        'brand_id',
        'model',
        'name',
        'subtitle',
        'description',
        'warranty',
        'availability_state',
        'status',
        'is_new',
        'is_featured',
        'release_date',
        'keywords',
        'seo_title',
        'seo_description',
        'published_at',
        'is_demo',
      ],
      products,
    ),
  );
  out.push(
    insert(
      'public.product_categories',
      ['product_id', 'category_id', 'is_primary', 'sort_order'],
      productCategories,
    ),
  );
  out.push(
    insert('public.product_options', ['id', 'product_id', 'key', 'name', 'sort_order'], options),
  );
  out.push(
    insert(
      'public.product_option_values',
      ['id', 'option_id', 'key', 'label', 'swatch_hex', 'sort_order'],
      values,
    ),
  );
  out.push(
    insert(
      'public.product_variants',
      [
        'id',
        'product_id',
        'sku',
        'price',
        'compare_at_price',
        'stock_quantity',
        'low_stock_threshold',
        'is_active',
        'is_default',
        'warranty',
        'sort_order',
        'is_demo',
      ],
      variants,
    ),
  );
  out.push(
    insert('public.variant_option_values', ['variant_id', 'option_id', 'option_value_id'], vov),
  );
  out.push(
    insert(
      'public.product_media',
      [
        'id',
        'product_id',
        'option_value_id',
        'kind',
        'url',
        'poster_url',
        'alt',
        'width',
        'height',
        'sort_order',
        'is_cover',
        'is_demo',
      ],
      media,
    ),
  );
  out.push(
    insert(
      'public.product_spec_groups',
      ['id', 'product_id', 'key', 'title', 'sort_order'],
      groups,
    ),
  );
  out.push(
    insert(
      'public.product_specs',
      ['id', 'group_id', 'key', 'label', 'value', 'sort_order'],
      specs,
    ),
  );
  out.push(
    insert(
      'public.product_relations',
      ['product_id', 'related_product_id', 'kind', 'sort_order'],
      relations,
    ),
  );
  out.push(
    insert('public.product_rankings', ['product_id', 'best_seller_score', 'source'], rankings),
  );

  out.push(
    insert(
      'public.offers',
      [
        'id',
        'slug',
        'kind',
        'title',
        'subtitle',
        'description',
        'badge',
        'cta_label',
        'cta_href',
        'discount_percent',
        'discount_amount',
        'bundle_price',
        'promo_code',
        'starts_at',
        'ends_at',
        'max_redemptions',
        'max_redemptions_per_customer',
        'min_subtotal',
        'show_countdown',
        'featured_on_home',
        'status',
        'sort_order',
        'is_demo',
      ],
      catalog.offers.map((o) => [
        id(o.id),
        q(o.slug),
        q(o.kind),
        jsonLiteral(o.title),
        jsonLiteral(o.subtitle),
        jsonLiteral(o.description),
        jsonLiteral(o.badge),
        jsonLiteral(o.cta?.label),
        q(o.cta?.href),
        num(o.discountPercent),
        num(o.discountAmount),
        num(o.bundlePrice),
        q(o.promoCode),
        time(o.startsAt),
        time(o.endsAt),
        num(o.maxRedemptions),
        num(o.maxRedemptionsPerCustomer),
        num(o.minSubtotal),
        bool(o.showCountdown),
        bool(o.featuredOnHome),
        "'published'",
        num(o.sortOrder),
        'true',
      ]),
    ),
  );
  out.push(
    insert(
      'public.offer_products',
      ['offer_id', 'product_id', 'role', 'sort_order'],
      catalog.offers.flatMap((o) =>
        o.products.map((p, i) => [id(o.id), id(`demo-product-${p.slug}`), q(p.role), num(i)]),
      ),
    ),
  );

  out.push(
    insert(
      'public.content_entries',
      [
        'id',
        'slug',
        'type',
        'eyebrow',
        'title',
        'subtitle',
        'excerpt',
        'body',
        'media_kind',
        'media_url',
        'media_alt',
        'cta_label',
        'cta_href',
        'secondary_cta_label',
        'secondary_cta_href',
        'state',
        'release_date',
        'publish_at',
        'expires_at',
        'is_featured',
        'status',
        'is_demo',
      ],
      catalog.entries.map((e) => [
        id(e.id),
        q(e.slug),
        q(e.type),
        jsonLiteral(e.eyebrow),
        jsonLiteral(e.title),
        jsonLiteral(e.subtitle),
        jsonLiteral(e.excerpt),
        jsonLiteral(e.body),
        q(e.media?.kind),
        q(e.media?.url),
        jsonLiteral(e.media?.alt),
        jsonLiteral(e.cta?.label),
        q(e.cta?.href),
        jsonLiteral(e.secondaryCta?.label),
        q(e.secondaryCta?.href),
        q(e.state),
        date(e.releaseDate),
        time(e.publishAt),
        time(e.expiresAt),
        bool(e.isFeatured),
        "'published'",
        'true',
      ]),
    ),
  );
  out.push(
    insert(
      'public.content_entry_products',
      ['entry_id', 'product_id', 'sort_order'],
      catalog.entries.flatMap((e) =>
        e.products.map((slug, i) => [id(e.id), id(`demo-product-${slug}`), num(i)]),
      ),
    ),
  );

  return `-- ════════════════════════════════════════════════════════════════════════════
-- MALEK STORE · DEMO seed (sample data for previews — every top-level row has is_demo = true)
-- GENERATED by scripts/seed/generate-seed-sql.mjs from supabase/seed/data/demo/catalog.json.
-- Do not edit by hand. Remove at any time with: select public.delete_all_demo_data();
-- Demo rows stay hidden from the live storefront unless features.showDemoCatalog is enabled
-- (staging only), and are always labelled "Demo" when shown.
-- Prices, stock and specifications are SAMPLE values, not real Malek Store data.
-- ════════════════════════════════════════════════════════════════════════════

begin;
${out.filter(Boolean).join('\n')}commit;
`;
}

async function main() {
  const outputs = [
    [path.join(seedDir, 'base.sql'), await buildBaseSql()],
    [path.join(seedDir, 'demo.sql'), await buildDemoSql()],
  ];
  let stale = false;
  for (const [file, content] of outputs) {
    if (checkOnly) {
      const current = await readFile(file, 'utf8').catch(() => '');
      if (current !== content) {
        console.error(`✗ ${path.relative(root, file)} is out of date — run npm run seed:generate`);
        stale = true;
      }
    } else {
      await writeFile(file, content);
      console.log(`✓ wrote ${path.relative(root, file)}`);
    }
  }
  if (stale) process.exit(1);
  if (checkOnly) console.log('✓ seed SQL is up to date');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
