// Concatenate all migrations into supabase/apply-all.sql (paste into the SQL editor if you prefer not to use the CLI).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const files = readdirSync(join(dir, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `-- ============ ${f} ============\n${readFileSync(join(dir, 'migrations', f), 'utf8')}`).join('\n');
writeFileSync(join(dir, 'apply-all.sql'), `-- ACCORD CRM V2 (Claude) — ALL migrations in order. Generated by scripts/build-apply-all.mjs. Run once on a NEW, EMPTY project.\n${body}`);
console.log(`apply-all.sql: ${files.length} migrations`);
